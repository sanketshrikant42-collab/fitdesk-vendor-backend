"""Cloud Backup metadata for FitDesk Pro.

The gym's actual data never passes through this backend: the desktop app
encrypts its SQLite backup locally (AES-256-GCM) and uploads it straight
to Cloudflare R2 with a short-lived presigned URL that this backend
issues for ONE exact object key. This module only stores *metadata*
about those objects plus each gym's (encrypted-at-rest) backup key.

Gym isolation: every row hangs off a licensing.Client, and every view
resolves that Client from the caller's validated license key + device --
never from a gym/client id the caller supplies. Object keys are always
built server-side under gyms/GYM-<client id>/..., so even a presigned
URL can only ever touch that one gym's prefix.
"""

import secrets
import uuid

from django.db import models
from django.utils import timezone

from licensing.models import Client, Device, License


def generate_key_id():
    return "gk1-" + secrets.token_hex(6)


class GymBackupKey(models.Model):
    """One per Client: the random 256-bit key that gym's desktop uses to
    encrypt its backups before they ever leave the machine.

    Stored ONLY encrypted (Fernet, with BACKUP_KEY_ENCRYPTION_KEY from the
    environment -- see cloud_backup/keys.py) and never written to R2, so
    a leak of the bucket alone does not expose any gym's data. It is
    handed back only to a device that presents a valid, active license
    for this same Client (that is what makes cloud restore onto a
    replacement PC possible)."""

    client = models.OneToOneField(Client, related_name="backup_key", on_delete=models.CASCADE)
    key_id = models.CharField(max_length=32, unique=True, default=generate_key_id)
    key_encrypted = models.TextField(help_text="Fernet-encrypted 32-byte key. Never shown in the admin.")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "Gym backup key"

    def __str__(self):
        return f"{self.client.gym_name} — {self.key_id}"


class CloudBackup(models.Model):
    STATUS_PENDING_UPLOAD = "pending_upload"
    STATUS_AVAILABLE = "available"
    STATUS_FAILED = "failed"
    STATUS_CORRUPT = "corrupt"
    STATUS_DELETION_PENDING = "deletion_pending"
    STATUS_DELETED = "deleted"
    STATUS_CHOICES = [
        (STATUS_PENDING_UPLOAD, "Pending upload"),
        (STATUS_AVAILABLE, "Available (verified)"),
        (STATUS_FAILED, "Upload failed"),
        (STATUS_CORRUPT, "Corrupt (verification failed)"),
        (STATUS_DELETION_PENDING, "Deletion pending"),
        (STATUS_DELETED, "Deleted"),
    ]

    TYPE_SCHEDULED = "scheduled"
    TYPE_MANUAL = "manual"
    TYPE_CHOICES = [
        (TYPE_SCHEDULED, "Scheduled (daily)"),
        (TYPE_MANUAL, "Manual"),
    ]

    # backup_id is generated by the DESKTOP (backups are created offline
    # first, uploaded later) -- so it is only unique per Client, and every
    # lookup is always filtered by the resolved Client as well.
    backup_id = models.UUIDField(default=uuid.uuid4, editable=False)
    client = models.ForeignKey(Client, related_name="cloud_backups", on_delete=models.CASCADE)
    license = models.ForeignKey(License, null=True, blank=True, related_name="cloud_backups", on_delete=models.SET_NULL)
    device = models.ForeignKey(Device, null=True, blank=True, related_name="cloud_backups", on_delete=models.SET_NULL)

    backup_type = models.CharField(max_length=12, choices=TYPE_CHOICES, default=TYPE_SCHEDULED)
    file_name = models.CharField(max_length=200)
    file_size = models.BigIntegerField()
    checksum_sha256 = models.CharField(max_length=64)
    # MD5 of the encrypted file (hex). Signed into the presigned PUT as
    # Content-MD5, so R2 itself rejects an upload whose body doesn't match,
    # and compared with the object's ETag at completion.
    content_md5 = models.CharField(max_length=32, blank=True)

    application_version = models.CharField(max_length=32, blank=True)
    database_version = models.CharField(max_length=32, blank=True)
    backup_format_version = models.PositiveIntegerField(default=1)
    encryption_algorithm = models.CharField(max_length=32, default="AES-256-GCM")
    encryption_key_id = models.CharField(max_length=32, blank=True)

    backup_created_at = models.DateTimeField(help_text="When the desktop created the backup (may be well before upload if it was offline).")
    created_at = models.DateTimeField(auto_now_add=True, help_text="When the upload was first requested.")
    completed_at = models.DateTimeField(null=True, blank=True)
    verified_at = models.DateTimeField(null=True, blank=True)
    deleted_at = models.DateTimeField(null=True, blank=True)

    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default=STATUS_PENDING_UPLOAD)
    object_key = models.CharField(max_length=300, unique=True)

    upload_requests = models.PositiveIntegerField(default=0)
    last_upload_request_at = models.DateTimeField(null=True, blank=True)
    deletion_attempts = models.PositiveIntegerField(default=0)
    last_error = models.CharField(max_length=255, blank=True)

    restore_requests = models.PositiveIntegerField(default=0)
    last_restore_request_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-backup_created_at"]
        constraints = [
            models.UniqueConstraint(fields=["client", "backup_id"], name="cloud_backup_unique_per_client"),
        ]
        indexes = [
            models.Index(fields=["client", "status", "backup_created_at"]),
        ]

    def __str__(self):
        return f"{self.client.gym_name} — {self.file_name} ({self.status})"

    @property
    def gym_ref(self):
        return gym_ref_for(self.client)

    def mark(self, status, error=""):
        self.status = status
        self.last_error = (error or "")[:255]
        fields = ["status", "last_error"]
        now = timezone.now()
        if status == self.STATUS_AVAILABLE:
            self.completed_at = self.completed_at or now
            self.verified_at = now
            fields += ["completed_at", "verified_at"]
        if status == self.STATUS_DELETED:
            self.deleted_at = now
            fields.append("deleted_at")
        self.save(update_fields=fields)


def gym_ref_for(client):
    """The stable, human-readable gym identifier used in R2 object keys
    and backup file names, e.g. GYM-00007. Derived from the Client's
    primary key on the server -- never accepted from a request."""
    return f"GYM-{client.pk:05d}"
